import * as React from "react"
import { cn } from "cn"

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        "group/card flex flex-col gap-(--card-spacing) overflow-hidden rounded-m bg-card py-(--card-spacing) type-s text-card-foreground shadow-(--shadow-m) [--card-spacing:var(--space-l)] has-[>img:first-child]:pt-0 data-[size=sm]:[--card-spacing:var(--space-m)] *:[img:first-child]:rounded-t-m *:[img:last-child]:rounded-b-m",
        className
      )}
      {...props}
    />
  )
}

